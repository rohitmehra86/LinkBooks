export type AiIntent =
  | "ask"
  | "explain"
  | "categorise"
  | "draft"
  | "duplicates"
  | "reconcile"
  | "unusual"
  | "navigate";

const INTENTS: AiIntent[] = [
  "ask",
  "explain",
  "categorise",
  "draft",
  "duplicates",
  "reconcile",
  "unusual",
  "navigate",
];

async function recordUsage(
  supabase: {
    rpc: (fn: string, args: Record<string, unknown>) => Promise<{ error: { message: string } | null }>;
  },
  args: {
    companyId: string;
    intent: string;
    status: string;
    provider?: string | null;
    model?: string | null;
    promptChars?: number;
    estimatedTokens?: number;
    latencyMs?: number | null;
    errorCode?: string | null;
  },
) {
  await supabase.rpc("record_ai_usage", {
    _company_id: args.companyId,
    _intent: args.intent,
    _status: args.status,
    _provider: args.provider ?? null,
    _model: args.model ?? null,
    _prompt_chars: args.promptChars ?? 0,
    _estimated_tokens: args.estimatedTokens ?? 0,
    _latency_ms: args.latencyMs ?? null,
    _error_code: args.errorCode ?? null,
  });
}

