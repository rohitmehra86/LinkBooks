export function roleHasPermission(role: CompanyRole, permission: Permission): boolean {
  return ROLE_PERMISSION_MATRIX[role].includes(permission);
}

/** Fail closed: unknown role gets no permissions. */
export function permissionsForRole(role: string | null | undefined): readonly Permission[] {
  if (!role || !(role in ROLE_PERMISSION_MATRIX)) return [];
  return ROLE_PERMISSION_MATRIX[role as CompanyRole];
}
